import re
from pathlib import Path

from jumpstarter.exporter.phase import mermaid

HOOKS_DOC = Path(__file__).resolve().parents[5] / "docs" / "source" / "introduction" / "hooks.md"


def test_documented_lifecycle_diagram_is_drawn_from_the_table():
    """The diagram in the hooks documentation is mermaid() pasted in: regenerate it when ALLOWED changes."""
    marker = "<!-- Generated by jumpstarter.exporter.phase.mermaid()"
    doc = HOOKS_DOC.read_text()
    match = re.search(re.escape(marker) + r".*?\n```\{mermaid\}\n(.*?)\n```", doc, re.DOTALL)
    assert match, f"no generated lifecycle diagram in {HOOKS_DOC}"
    assert match.group(1) == mermaid()
